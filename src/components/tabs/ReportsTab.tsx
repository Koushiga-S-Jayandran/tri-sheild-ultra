import React, { useState } from 'react';
import { 
  FileText, Download, CheckCircle2, AlertTriangle, 
  Send, ShieldAlert, Lock, ExternalLink, Printer
} from 'lucide-react';
import { jsPDF } from 'jspdf';
import { EvidenceBlock, CellularReading, DetectionResult } from '../../types/trishield';
import { TermTooltip } from '../TermTooltip';

interface ReportsTabProps {
  evidenceChain: EvidenceBlock[];
  activeIncidentIndex: number;
  onSelectIncident: (index: number) => void;
}

export const ReportsTab: React.FC<ReportsTabProps> = ({
  evidenceChain,
  activeIncidentIndex,
  onSelectIncident
}) => {
  const [confirmedFiling, setConfirmedFiling] = useState(false);
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false);
  const [copiedFilingText, setCopiedFilingText] = useState(false);

  // Selected incident
  const currentBlock = evidenceChain[activeIncidentIndex] || evidenceChain[evidenceChain.length - 1];
  const reading = currentBlock ? currentBlock.reading : null;
  const detection = currentBlock ? currentBlock.detection : null;

  // Filter only high risk incidents or all
  const highRiskIncidents = evidenceChain.filter(b => b.detection.riskScore >= 50);

  // Pre-filled filing text for cybercrime.gov.in / National Helpline 1930
  const filingTemplate = `[INCIDENT COMPLAINT: ILLEGAL ROGUE BASE STATION / IMSI CATCHER]
Target Reference: National Cyber Crime Reporting Portal (cybercrime.gov.in / Helpline 1930)
Generated by: TriShield SOC (Cryptographically Verified Forensic Export)
Incident Timestamp: ${reading?.timestamp || new Date().toISOString()}

1. TECHNICAL SUMMARY OF SUSPECT TRANSMITTER:
- Broadcast Cell ID: ${reading?.cellId}
- Location Area Code (LAC): ${reading?.lac}
- Radio Frequency Channel (ARFCN): ${reading?.arfcn}
- Measured RF Power (RSSI): ${reading?.rssi} dBm (Abnormal power override)
- Forced Protocol State: ${reading?.encryption}
- Geographic Coordinates: ${reading?.lat.toFixed(5)}° N, ${reading?.lng.toFixed(5)}° E

2. DETECTED THREAT INDICATORS:
- Threat Risk Score: ${detection?.riskScore}/100 [SEVERITY: ${detection?.severity}]
- Primary Anomaly: Forced A5/0 null cipher / unauthorized broadcast reselection bias (+${reading?.c2ReselectionBias}dB).
- Suppression: Handset isolated with zero adjacent carrier neighbor broadcasts.
- Plain-English Impact: Potential interception of subscriber voice, SMS OTPs, and clandestine location harvesting.

3. FORENSIC CHAIN OF CUSTODY (SHA-256):
- Block Index: #${currentBlock?.index}
- Previous Hash: ${currentBlock?.prevHash}
- Sealed Hash Seal: ${currentBlock?.hash}
- Integrity Status: VERIFIED UNALTERED

[NOTICE: This document is prepared for lawful law-enforcement submission. TriShield did not transmit RF spectrum.]`;

  const handleGeneratePdf = () => {
    if (!currentBlock || !reading || !detection) return;
    setIsGeneratingPdf(true);

    try {
      const doc = new jsPDF();

      // Header Banner
      doc.setFillColor(14, 17, 23);
      doc.rect(0, 0, 210, 40, 'F');
      
      doc.setTextColor(240, 246, 252);
      doc.setFontSize(18);
      doc.text('TRISHIELD FORENSIC INCIDENT REPORT', 14, 20);

      doc.setFontSize(10);
      doc.setTextColor(88, 166, 255);
      doc.text('Rogue Cell Tower & IMSI Catcher Interception Dossier', 14, 28);
      doc.setTextColor(139, 148, 158);
      doc.text(`Reference: cybercrime.gov.in / 1930 · Generated: ${new Date().toLocaleString()}`, 14, 35);

      // Section 1: Executive Summary
      doc.setTextColor(14, 17, 23);
      doc.setFontSize(14);
      doc.text('1. Incident Executive Summary', 14, 52);

      doc.setFontSize(10);
      doc.setTextColor(60, 60, 60);
      doc.text(`Severity Level: ${detection.severity}`, 14, 60);
      doc.text(`Fused Threat Risk Score: ${detection.riskScore} / 100`, 14, 66);
      doc.text(`Target Handset ID: ${reading.deviceId}`, 14, 72);
      doc.text(`Timestamp: ${reading.timestamp}`, 14, 78);
      doc.text(`Estimated Location: ${reading.lat.toFixed(5)} N, ${reading.lng.toFixed(5)} E`, 14, 84);

      // Section 2: Technical Telemetry
      doc.setTextColor(14, 17, 23);
      doc.setFontSize(14);
      doc.text('2. Radio Frequency & Protocol Breakdown', 14, 98);

      doc.setFontSize(10);
      doc.setTextColor(60, 60, 60);
      doc.text(`• Cell Tower Identifier: ${reading.cellId}`, 14, 106);
      doc.text(`• Location Area Code (LAC): ${reading.lac}`, 14, 112);
      doc.text(`• Downlink Channel (ARFCN): ${reading.arfcn}`, 14, 118);
      doc.text(`• Received Signal Strength (RSSI): ${reading.rssi} dBm`, 14, 124);
      doc.text(`• Cipher Negotiation: ${reading.encryption}`, 14, 130);
      doc.text(`• Advertised Adjacent Neighbors: ${reading.neighborCount}`, 14, 136);

      // Section 3: Threat Reasons
      doc.setTextColor(14, 17, 23);
      doc.setFontSize(14);
      doc.text('3. Triggered Security Violations', 14, 150);

      let yPos = 158;
      detection.ruleContributions.filter(r => r.triggered).forEach((rule) => {
        doc.setFontSize(9);
        doc.setTextColor(200, 30, 30);
        doc.text(`[VIOLATION +${rule.points} pts] ${rule.name}`, 14, yPos);
        yPos += 5;
        doc.setTextColor(80, 80, 80);
        doc.text(rule.explanation, 18, yPos);
        yPos += 8;
      });

      // Section 4: Cryptographic Seal
      doc.setTextColor(14, 17, 23);
      doc.setFontSize(14);
      doc.text('4. SHA-256 Tamper-Evident Chain Seal', 14, yPos + 6);

      doc.setFontSize(8);
      doc.setTextColor(30, 30, 30);
      doc.text(`Block Ledger Index: #${currentBlock.index}`, 14, yPos + 14);
      doc.text(`Previous Hash: ${currentBlock.prevHash}`, 14, yPos + 20);
      doc.text(`Sealed SHA-256: ${currentBlock.hash}`, 14, yPos + 26);
      doc.text('Digital Signature Status: MATHEMATICALLY SEALED & VERIFIED', 14, yPos + 32);

      // Footer
      doc.setFontSize(8);
      doc.setTextColor(120, 120, 120);
      doc.text('Notice: TriShield operates passively and never transmits on cellular frequencies.', 14, 285);

      doc.save(`TriShield_Forensic_Report_Cell_${reading.cellId}.pdf`);
    } catch (e) {
      console.error(e);
    } finally {
      setIsGeneratingPdf(false);
    }
  };

  const handleDownloadSessionSummary = () => {
    const summaryData = {
      generatedAt: new Date().toISOString(),
      system: 'TriShield Rogue Cell Tower Detection System v2.4',
      totalReadings: evidenceChain.length,
      chainStatus: 'VERIFIED',
      incidents: evidenceChain.map(b => ({
        blockIndex: b.index,
        timestamp: b.timestamp,
        cellId: b.reading.cellId,
        lac: b.reading.lac,
        rssi: b.reading.rssi,
        encryption: b.reading.encryption,
        riskScore: b.detection.riskScore,
        severity: b.detection.severity,
        sha256Hash: b.hash
      }))
    };

    const blob = new Blob([JSON.stringify(summaryData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `TriShield_Session_Summary_${Date.now()}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyFiling = () => {
    navigator.clipboard?.writeText(filingTemplate);
    setCopiedFilingText(true);
    setTimeout(() => setCopiedFilingText(false), 2500);
  };

  return (
    <div className="p-6 space-y-6 max-w-7xl mx-auto">
      {/* Header */}
      <div className="p-5 rounded-xl bg-[#161B22] border border-[#21262D] flex flex-wrap items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-[#1F6FEB]" />
            <h2 className="text-base font-bold text-[#F0F6FC]">
              Law-Enforcement Incident Reporting &amp; Cybercrime Dossier
            </h2>
          </div>
          <p className="text-xs text-[#8B949E] mt-0.5">
            Generates standardized legal dossiers formatted for the National Cyber Crime Reporting Portal (cybercrime.gov.in / 1930).
          </p>
        </div>

        <div className="flex items-center gap-3">
          <button
            onClick={handleDownloadSessionSummary}
            className="px-3.5 py-1.5 bg-[#21262D] hover:bg-[#30363D] text-[#E6EDF3] text-xs font-semibold rounded-lg border border-[#30363D] flex items-center gap-1.5 transition-colors cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 text-[#58A6FF]" />
            <span>Download Session Summary (JSON)</span>
          </button>
        </div>
      </div>

      {/* Main Reporting Workspace */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Column: Incident Selector & Details (5 cols) */}
        <div className="lg:col-span-5 space-y-6">
          <div className="soc-card p-5 space-y-4">
            <div className="flex items-center justify-between border-b border-[#21262D] pb-3">
              <h3 className="text-xs font-bold uppercase tracking-wider text-[#F0F6FC]">
                1. Select Incident From Evidence Ledger
              </h3>
              <span className="text-xs font-mono text-[#8B949E]">{evidenceChain.length} events logged</span>
            </div>

            <select
              value={activeIncidentIndex}
              onChange={(e) => {
                onSelectIncident(Number(e.target.value));
                setConfirmedFiling(false);
              }}
              className="w-full bg-[#0E1117] border border-[#30363D] text-[#E6EDF3] text-xs rounded-lg p-2.5 font-mono cursor-pointer focus:border-[#1F6FEB]"
            >
              {evidenceChain.map((b) => (
                <option key={b.index} value={b.index}>
                  Block #{b.index} · Cell {b.reading.cellId} · Score {b.detection.riskScore}/100 [{b.detection.severity}]
                </option>
              ))}
            </select>

            {/* Incident Summary Card */}
            {reading && detection && (
              <div className="p-4 rounded-lg bg-[#0E1117] border border-[#21262D] space-y-3">
                <div className="flex items-center justify-between">
                  <span className="text-xs text-[#8B949E]">Suspect Transmitter:</span>
                  <span className="font-mono text-xs font-bold text-[#F0F6FC]">
                    Cell #{reading.cellId} (LAC {reading.lac})
                  </span>
                </div>
                <div className="flex items-center justify-between">
                  <span className="text-xs text-[#8B949E]">Threat Index:</span>
                  <span className={`font-mono text-xs font-bold ${
                    detection.riskScore >= 60 ? 'text-[#EF4444]' : 'text-[#22C55E]'
                  }`}>
                    {detection.riskScore} / 100 ({detection.severity})
                  </span>
                </div>
                <div className="flex items-center justify-between">
                  <span className="text-xs text-[#8B949E]">Negotiated Encryption:</span>
                  <span className="font-mono text-xs text-[#E6EDF3]">
                    {reading.encryption}
                  </span>
                </div>
                <div className="flex items-center justify-between">
                  <span className="text-xs text-[#8B949E]">Signal Power:</span>
                  <span className="font-mono text-xs text-[#E6EDF3]">
                    {reading.rssi} dBm
                  </span>
                </div>
                <div className="pt-2 border-t border-[#21262D] text-xs text-[#8B949E]">
                  <span className="font-semibold text-[#F0F6FC] block mb-0.5">Plain-English Summary:</span>
                  {detection.plainEnglishReason}
                </div>
              </div>
            )}

            {/* PDF Generation Action */}
            <button
              onClick={handleGeneratePdf}
              disabled={isGeneratingPdf || !currentBlock}
              className="w-full py-2.5 px-4 bg-[#1F6FEB] hover:bg-[#388BFD] text-white text-xs font-semibold rounded-lg flex items-center justify-center gap-2 transition-colors cursor-pointer shadow-md"
            >
              <Download className="w-4 h-4" />
              <span>{isGeneratingPdf ? 'Generating Forensic PDF...' : 'Generate Law Enforcement PDF Report'}</span>
            </button>
          </div>
        </div>

        {/* Right Column: Two-Step Filing Confirmation Flow (7 cols) */}
        <div className="lg:col-span-7 soc-card p-5 flex flex-col justify-between">
          <div className="space-y-4">
            <div className="flex items-center justify-between border-b border-[#21262D] pb-3">
              <div className="flex items-center gap-2">
                <ShieldAlert className="w-4 h-4 text-[#F59E0B]" />
                <h3 className="text-xs font-bold uppercase tracking-wider text-[#F0F6FC]">
                  2. Indian Cybercrime Portal (1930) Preparation Flow
                </h3>
              </div>
              <span className="text-[11px] text-[#8B949E] italic">Strict 2-Step Confirmation</span>
            </div>

            <div className="p-3 rounded-lg bg-[#21262D]/60 border border-[#30363D] text-xs text-[#8B949E] leading-relaxed">
              <strong className="text-[#F0F6FC] block mb-1">Non-Negotiable Ethical &amp; Safety Boundary:</strong>
              TriShield <span className="text-[#EF4444] font-semibold">NEVER</span> automatically submits incident reports to government servers or public law enforcement portals. An operator must review the dossier and explicitly confirm preparation.
            </div>

            {/* Step 1: Confirm Button */}
            {!confirmedFiling ? (
              <div className="p-6 rounded-xl bg-[#0E1117] border border-[#21262D] text-center space-y-4">
                <div className="w-12 h-12 rounded-full bg-[#1F6FEB]/15 text-[#1F6FEB] flex items-center justify-center mx-auto">
                  <Lock className="w-6 h-6" />
                </div>
                <div>
                  <h4 className="text-sm font-semibold text-[#F0F6FC]">
                    Step 1: Confirm Incident &amp; Prepare Filing Text
                  </h4>
                  <p className="text-xs text-[#8B949E] max-w-md mx-auto mt-1">
                    Clicking below compiles the verified SHA-256 evidence block into a structured legal complaint ready for copy-pasting into cybercrime.gov.in.
                  </p>
                </div>
                <button
                  onClick={() => setConfirmedFiling(true)}
                  className="py-2.5 px-6 bg-[#22C55E] hover:bg-[#16A34A] text-black font-bold text-xs rounded-lg transition-colors cursor-pointer shadow-md inline-flex items-center gap-2"
                >
                  <CheckCircle2 className="w-4 h-4" />
                  <span>Confirm &amp; Prepare for Filing</span>
                </button>
              </div>
            ) : (
              /* Step 2: Pre-filled Complaint Text */
              <div className="space-y-3">
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2 text-xs text-[#22C55E] font-semibold font-mono">
                    <CheckCircle2 className="w-4 h-4" />
                    <span>Filing Dossier Prepared (Ready for Review)</span>
                  </div>
                  <button
                    onClick={handleCopyFiling}
                    className="px-3 py-1 bg-[#1F6FEB] hover:bg-[#388BFD] text-white text-xs font-semibold rounded flex items-center gap-1.5 transition-colors cursor-pointer"
                  >
                    <span>{copiedFilingText ? 'Copied to Clipboard!' : 'Copy Complaint Text'}</span>
                  </button>
                </div>

                <textarea
                  readOnly
                  rows={11}
                  value={filingTemplate}
                  className="w-full bg-[#090D13] border border-[#30363D] rounded-lg p-3 text-[11px] font-mono text-[#E6EDF3] leading-relaxed resize-none focus:outline-none"
                />

                <div className="flex items-center justify-between text-[11px] text-[#8B949E] pt-2">
                  <span>Target Portal: https://cybercrime.gov.in | National Toll-Free: 1930</span>
                  <a
                    href="https://cybercrime.gov.in"
                    target="_blank"
                    rel="noreferrer"
                    className="text-[#58A6FF] hover:underline flex items-center gap-1"
                  >
                    <span>Visit Portal</span>
                    <ExternalLink className="w-3 h-3" />
                  </a>
                </div>
              </div>
            )}
          </div>

          <p className="text-[11px] text-[#8B949E] mt-4 border-t border-[#21262D] pt-2">
            Reports pair mathematical proof with plain language. Judges can examine both the exportable PDF and the formatted filing draft.
          </p>
        </div>
      </div>
    </div>
  );
};
